def test_card_takes_its_own_name_and_maker_first():
    p = F.pub_entry("photo")
    assert S.card_for("rig", p) == {"title": "Rig", "href": "/devices/rig/", "image": "/media/sensors/rig/rig.jpg", "alt": "The rig",
                                    "maker": "Maker Co", "type": "Stereo module", "tags": p["card"]["tags"],
                                    "components": {"cameras": [{"maker": "OmniVision", "part": "OV9282", "count": 2, "src": "Maker", "via": "Datasheet",
                                                                "url": "https://example.com/d"}],
                                                   "imus": [{"maker": "Bosch", "part": "BMI088", "count": 1, "src": "Teardown", "via": "A teardown"}]}}
    p["card"]["maker"] = "Short"
    assert S.card_for("rig", p)["maker"] == "Short"
    q = F.pub_entry("old")
    assert S.card_for("o", q)["maker"] is None and S.card_for("o", q)["title"] == "Rig old"  # a maker without a link isn't named
    del q["header"]["maker"]
    assert S.card_for("o", q)["maker"] is None


def test_mdx_for_a_datasheet_and_an_older_page():
    m = S.mdx("rig", F.pub_entry("photo"))
    assert m.startswith('---\ntitle: "Rig photo"\ndescription: "Rig photo camera–IMU calibration with MVIS: A test rig."\npageType: example\n'
                        'wide: true\nsensor: rig\nhead:\n  - tag: title\n    content: "Rig photo camera–IMU calibration | OpenMVIS"\n---\n')
    assert f"Generated by {S.GENERATOR}. Edit the data" in m and S.GENERATOR.startswith("site/scripts/export_sensors.py ")
    assert m.count("<SensorPage") == len(S.HEADER_PARTS) and 'part="lead"' not in m
    old = F.pub_entry("old")
    del old["header"]
    m = S.mdx("old", old)
    assert "sensor: old" not in m and "head:" not in m and 'description: "A test rig."' in m and m.count("<SensorPage") == len(S.PARTS) + 1 and 'part="lead"' in m


def test_sensor_pages_live_under_the_sensor_wiki():
    assert S.SENSOR_BASE == "/devices/"
    assert "import SensorPage from '../../../components/SensorPage.astro';" in S.mdx("rig", F.pub_entry("photo"))
    text = S.overview_mdx(F.pub_doc())
    assert text.startswith("---\ntitle: Device wiki\n") and "import SensorGrid from '../../../components/SensorGrid.astro';" in text
    assert "](/benchmark/results/)" in text and "/benchmark/leaderboard/" not in text


def test_site_css_scopes_the_page_css():
    css = S.site_css(assets.page_css(), assets.header_css())
    assert css.startswith(f"/* Generated by {S.GENERATOR}. */\n.sp{{") and ".cards" not in css and "@media(max-width:1250px)" not in css
    assert assets.header_css() in css


def test_spot_rewrites_the_player_and_refuses_a_changed_one():
    js = S.spot(assets.progress_js())
    assert "SP_SPEED" in js and "' s of '" in js
    with pytest.raises(RuntimeError, match="update spot"):
        S.spot("changed player")


