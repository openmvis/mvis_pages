def test_groups_follow_the_pub_order_and_drop_empty_groups():
    pub = F.pub_doc()
    assert S.sensor_groups(pub) == [{"title": "Group One", "slugs": ["rig-photo", "rig-groups"]}, {"title": "Group Two", "slugs": ["rig-old"]}]
    assert [n["link"] for n in S.sensor_nav(pub)] == ["/devices/rig-photo/", "/devices/rig-groups/", "/devices/rig-old/"]


def test_sensor_without_a_known_group_fails():
    pub = F.pub_doc()
    pub["sensors"]["rig-old"]["group"] = "nope"
    with pytest.raises(ValueError, match="nope"):
        S.sensor_nav(pub)
    del pub["sensors"]["rig-old"]["group"]
    with pytest.raises(ValueError):
        S.sensor_groups(pub)


def test_overview_has_a_heading_per_group_and_every_sensor_once():
    pub = F.pub_doc()
    text = S.overview_mdx(pub)
    assert "[Group One](#group-one) · [Group Two](#group-two)" in text and "Empty" not in text
    for slug in pub["sensors"]:
        assert text.count(f'"{slug}"') == 1, slug


def test_sensor_json(variant):
    p = F.pub_entry("photo")
    parts = {k: k for k in ["header", "lead", "map", "hardware", *(k for _, k in S.HEADER_PARTS)]}
    j = S.sensor_json("rig", p, parts, [variant])
    assert list(j["parts"]) == ["header", *(k for _, k in S.HEADER_PARTS)]   # the unrendered parts are left out
    assert j["procs"] == ["/media/sensors/rig/process0.json"] and j["plotly"] == S.PLOTLY_LOCAL and j["card"]["href"] == "/devices/rig/"


def test_committed_sensor_css_matches_the_lib():
    """The site loads site/src/data/sensors/sensor.css, an exported copy of the lib's page CSS. A lib CSS change that
    isn't re-exported stays off the site (2026-11-15: the mid-frame td note ran into its value). Re-export with
    site/scripts/export_sensors.py, or write site_css(...) into the part before the views marker."""
    from pathlib import Path
    committed = (Path(__file__).resolve().parents[2] / "site/src/data/sensors/sensor.css").read_text()
    lib_part = committed.split("\n/* MVIS canvas views (mvis.analysis.views) */\n", 1)[0]
    assert lib_part == S.site_css(assets.page_css(), assets.header_css())
